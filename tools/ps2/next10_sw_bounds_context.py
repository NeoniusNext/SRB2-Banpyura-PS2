"""Link a bounds opt-out control, optionally atop checked existing IR opt-outs.

Consumes one EE compiler/LTO worker, jobs=1, and never starts an emulator.
All canonical IR inputs, metadata, engine and ELF remain byte-identical.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import time

ROOT=Path(__file__).resolve().parents[2]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(command,log,timeout):
    start=time.monotonic()
    result=subprocess.run(list(map(str,command)),cwd=ROOT,capture_output=True,text=True,timeout=timeout)
    log.write_text(' '.join(map(str,command))+'\n'+result.stdout+result.stderr)
    if result.returncode:raise SystemExit('Control build failed: '+str(log))
    return result.stdout,result.stderr,time.monotonic()-start


def archive_generated(out,inputs,recovery_paths=(),after_control=False):
    entries=[]
    for name,digest in inputs.items():
        original=Path(name);original=original if original.is_absolute() else ROOT/original
        if original.name!='config.h' or original.parent.name!='gen':continue
        candidates=[original,*map(Path,recovery_paths)]
        source=next((path for path in candidates if path.is_file() and sha(path)==digest),None)
        if source is None:raise SystemExit('No byte-exact recovery of pinned generated input '+name)
        group=hashlib.sha256(str(original.parent.resolve()).encode()).hexdigest()[:16]
        target=out/'generated-inputs'/group/original.name;target.parent.mkdir(parents=True,exist_ok=True)
        data=source.read_bytes()
        if target.exists() and target.read_bytes()!=data:raise SystemExit('Refusing different generated-input archive bytes')
        target.write_bytes(data)
        if sha(target)!=digest:raise SystemExit('Generated input archive differs from pinned bytes')
        entries.append({'original_path':name,'original_pinned_sha256':digest,'recovered_from':str(source.resolve()),
                        'archive_path':str(target.resolve()),'archive_sha256':sha(target)})
    if not entries:raise SystemExit('Expected at least one pinned generated config input')
    result={'archival_timing':'after completed control; byte-exact pinned-hash recovery' if after_control else 'before control compilation',
            'entries':entries,'all_original_pinned_hashes_equal_archive_hashes':True}
    path=out/'generated-input-archive.json';path.write_text(json.dumps(result,indent=2)+'\n')
    return {'path':str(path.resolve()),'sha256':sha(path),'details':result}


def main():
    import build as B
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--build',type=Path,required=True)
    p.add_argument('--snapshot',type=Path,required=True,help='frozen tree containing src/')
    p.add_argument('--out',type=Path,required=True)
    p.add_argument('--replace-ir',action='append',default=[],metavar='SOURCE=OBJECT',
                   help='reuse an existing checked replacement IR object without changing the canonical build')
    p.add_argument('--replacement-report',type=Path,
                   help='report.json pinning replacement objects and the identical canonical IR graph')
    a=p.parse_args();build=a.build.resolve();out=a.out.resolve();snapshot=a.snapshot.resolve()
    if not out.is_relative_to(ROOT/'build'):raise SystemExit('Control output must be under build/')
    out.mkdir(parents=True,exist_ok=True)
    report_path=build/'build-report.json';report=json.loads(report_path.read_text())
    canonical_engine=build/'obj/engine_lto.o';canonical_elf=build/'SRB2.ELF'
    if sha(canonical_elf)!=report['elf_sha256']:raise SystemExit('Canonical ELF/report disagreement')
    canonical_engine_hash=sha(canonical_engine);canonical_elf_hash=sha(canonical_elf)
    # Every canonical project source/header dependency is pinned to the frozen
    # source context before compiling the single opt-out IR replacement.
    snapshot_inputs={}
    for name,digest in report['input_sha256'].items():
        path=Path(name)
        if path.is_relative_to(ROOT/'src'):
            frozen=snapshot/'src'/path.relative_to(ROOT/'src')
            if sha(frozen)!=digest:raise SystemExit('Snapshot differs from canonical project input '+name)
            snapshot_inputs[str(frozen)]=digest
    source=snapshot/'src/r_plane.c'
    if str(source) not in snapshot_inputs:raise SystemExit('Canonical bounds source is not pinned')
    flags=[f for f in report['flags'] if f not in ('-MMD','-MP')]
    root_src='-I'+str(ROOT/'src')
    flags=['-I'+str(snapshot/'src')+f[len(root_src):] if f.startswith(root_src) else f for f in flags]
    # Freeze exact canonical generated bytes before compiling; a copied full
    # build can recover its recorded config from its own immutable gen/ tree.
    external_inputs={name:digest for name,digest in report['input_sha256'].items()
                     if not Path(name).is_relative_to(ROOT/'src')}
    generated_archive=archive_generated(out,external_inputs,[build/'gen/config.h'])
    generated_names={entry['original_path'] for entry in generated_archive['details']['entries']}
    direct_external_inputs={name:digest for name,digest in external_inputs.items() if name not in generated_names}
    for name,digest in direct_external_inputs.items():
        if sha(Path(name))!=digest:raise SystemExit('Canonical external input changed '+name)
    generated_include_paths={str(Path(entry['original_path']).parent.resolve()):str(Path(entry['archive_path']).parent)
                             for entry in generated_archive['details']['entries']}
    flags=['-I'+generated_include_paths.get(str(Path(f[2:]).resolve()),f[2:]) if f.startswith('-I') else f for f in flags]
    if '-flto' not in flags or B.UNIT_FLAGS.get('src/r_plane.c'):
        raise SystemExit('Expected default LTO and no hidden bounds-unit flags')
    flags+=['-DPS2_NOOPT_PLANEBOUNDS_MMI','-Werror']
    compiler=report['link_command'][0];replacement=out/'r_plane.o'
    compile_command=[compiler,*flags,'-MMD','-MF',str(out/'r_plane.d'),'-c',str(source),'-o',str(replacement)]
    stdout,stderr,compile_seconds=run(compile_command,out/'compile.log',120)
    if stdout or stderr:raise SystemExit('Bounds control compile has diagnostics')
    objects=[build/'obj'/name.replace('/','__').replace('.c','.o') for name in report['sources']]
    if report['hardware']:
        objects+=[build/'obj'/(name+'_vsm.o') for name in ('ps2_hw_vu1','ps2_hw_vu1_spr')]
    canonical_hashes={str(path):sha(path) for path in objects}
    old=build/'obj/src__r_plane.o'
    if objects.count(old)!=1:raise SystemExit('Expected one canonical bounds IR unit')
    selected=[replacement if path==old else path for path in objects]
    imported=[]
    if a.replace_ir:
        if not a.replacement_report:raise SystemExit('Imported IR needs its complete canonical/replacement report')
        imported_report_path=a.replacement_report.resolve();imported_report=json.loads(imported_report_path.read_text())
        if imported_report['canonical_objects']!=canonical_hashes or imported_report['canonical_engine_sha256']!=canonical_engine_hash or imported_report['canonical_elf_sha256']!=canonical_elf_hash:
            raise SystemExit('Imported replacement report has a different canonical IR/engine/ELF context')
        seen=set()
        for item in a.replace_ir:
            if '=' not in item:raise SystemExit('Expected SOURCE=OBJECT replacement')
            unit,object_path=item.split('=',1);object_path=Path(object_path).resolve()
            if unit in seen or unit=='src/r_plane.c' or unit not in report['sources']:
                raise SystemExit('Duplicate, missing, or reserved replacement source '+unit)
            seen.add(unit);original=build/'obj'/unit.replace('/','__').replace('.c','.o')
            digest=sha(object_path)
            if imported_report['objects'].get(str(object_path))!=digest:
                raise SystemExit('Imported IR bytes differ from the checked replacement report')
            if selected.count(original)!=1:raise SystemExit('Expected one exact imported IR input position')
            selected[selected.index(original)]=object_path
            imported.append({'unit':unit,'canonical_object':str(original),'canonical_sha256':canonical_hashes[str(original)],
                             'replacement_object':str(object_path),'replacement_sha256':digest,
                             'replacement_report':str(imported_report_path),'replacement_report_sha256':sha(imported_report_path)})
    elif a.replacement_report:raise SystemExit('Replacement report supplied without an imported IR object')
    merged=out/'engine_lto.o'
    lto_command=[compiler,'-r','-nostdlib','-flto=1','-flinker-output=nolto-rel','-O2',
                 '-ffunction-sections','-fdata-sections',
                 *[f for f in flags if f.startswith('-G') or f=='-mno-abicalls'],
                 *map(str,selected),'-o',str(merged)]
    stdout,stderr,lto_seconds=run(lto_command,out/'lto.log',360)
    canonical_lto_diagnostics=(build/'lto.log').read_text()
    # The canonical invocation may spell repository inputs relatively, while
    # this isolated control resolves them absolutely. Compare every diagnostic
    # after only removing that exact repository prefix; do not filter warnings.
    normalize_paths=lambda text:text.replace(str(ROOT)+'/', '')
    if stdout or normalize_paths(stderr)!=normalize_paths(canonical_lto_diagnostics):
        raise SystemExit('Control LTO diagnostics differ from canonical build')
    control_lto_diagnostics=stderr
    link=list(report['link_command']);indices=[i for i,arg in enumerate(link) if arg.endswith('/engine_lto.o')]
    if len(indices)!=1:raise SystemExit('Expected one exact canonical engine input')
    link[indices[0]]=str(merged);link[link.index('-o')+1]=str(out/'SRB2.ELF')
    indices=[i for i,arg in enumerate(link) if arg.startswith('-Wl,-Map=')]
    if len(indices)!=1:raise SystemExit('Expected one exact canonical map argument')
    link[indices[0]]='-Wl,-Map='+str(out/'SRB2.map')
    stdout,stderr,link_seconds=run(link,out/'link.log',120)
    diagnostics='\n'.join(line for line in (stdout+stderr).splitlines()
                          if 'linking abicalls files with non-abicalls files' not in line).strip()
    if diagnostics:raise SystemExit('Control final link has diagnostics')
    if canonical_hashes!={str(path):sha(path) for path in objects} or canonical_engine_hash!=sha(canonical_engine) or canonical_elf_hash!=sha(canonical_elf):
        raise SystemExit('Canonical IR/engine/ELF changed during control construction')
    for entry in imported:
        if sha(Path(entry['replacement_object']))!=entry['replacement_sha256'] or sha(Path(entry['replacement_report']))!=entry['replacement_report_sha256']:
            raise SystemExit('Imported IR or its checked report changed during control construction')
    for name,digest in {**snapshot_inputs,**direct_external_inputs}.items():
        if sha(Path(name))!=digest:raise SystemExit('Pinned build input changed during control construction '+name)
    for entry in generated_archive['details']['entries']:
        if sha(Path(entry['archive_path']))!=entry['original_pinned_sha256']:
            raise SystemExit('Actual archived generated input changed during control construction')
    control={'only_recompiled_unit':'src/r_plane.c','only_added_definition':'PS2_NOOPT_PLANEBOUNDS_MMI',
             'canonical_build':str(build),'canonical_report_sha256':sha(report_path),
             'canonical_engine_sha256':canonical_engine_hash,'canonical_ELF_sha256':canonical_elf_hash,
             'canonical_IR_objects':canonical_hashes,'control_IR_objects':{str(path):sha(path) for path in selected},
             'compile_command':compile_command,'lto_command':lto_command,'link_command':link,
             'compile_seconds':compile_seconds,'lto_seconds':lto_seconds,'link_seconds':link_seconds,
             'lto_diagnostics':{'canonical':canonical_lto_diagnostics,'control':control_lto_diagnostics,
                 'normalization':'remove exact repository-root path prefix only',
                 'all_normalized_diagnostics_identical':True},
             'frozen_project_inputs':snapshot_inputs,'external_generated_inputs':external_inputs,
             'generated_input_archive':generated_archive,
             'additional_checked_IR_replacements':imported,
             'all_other_IR_inputs_and_generated_metadata_preserved':True,
             'engine_sha256':sha(merged),'ELF_sha256':sha(out/'SRB2.ELF')}
    result=dict(report);result.update(link_command=link,compiled=1,elf_sha256=control['ELF_sha256'],
        elf_bytes=(out/'SRB2.ELF').stat().st_size,bounds_context_control=control)
    (out/'build-report.json').write_text(json.dumps(result,indent=2)+'\n')
    (out/'context-report.json').write_text(json.dumps(control,indent=2)+'\n')
    print('Built exact current-header one-unit bounds opt-out control: '+str(out))


if __name__=='__main__':main()
